"""Read-only SQLite diagnostics and consistent local backups.

No database initialization, migrations, restore or data mutation happens here.
Backups are ZIP archives containing an SQLite online snapshot, photo evidence,
and an SHA-256 manifest. Private files never enter Git.
"""
import argparse
from contextlib import closing
from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path
import sqlite3
import sys
import tempfile
import zipfile

from .database import DATABASE_URL, ROOT
from .version import APP_VERSION


REQUIRED_TABLES = (
    "drawers", "medicines", "stock_items", "review_records",
    "review_decisions", "source_images", "inventory_events",
    "substance_evidence",
    "registered_products", "registered_substances",
    "registered_compositions", "medicine_registration_links", "registry_link_events",
    "grls_import_batches", "grls_import_rows",
)


class MaintenanceError(RuntimeError):
    """Expected, human-readable local operations error."""


def database_path(url=None):
    url = DATABASE_URL if url is None else url
    if not url.startswith("sqlite:///") or url.endswith(":memory:"):
        raise MaintenanceError("Поддерживается только файловая база SQLite.")
    return Path(url[len("sqlite:///"):]).expanduser().resolve()


def _open_readonly(path):
    if not path.is_file():
        raise MaintenanceError("Локальная база отсутствует: " + str(path))
    conn = sqlite3.connect(path.as_uri() + "?mode=ro", uri=True, timeout=8)
    conn.execute("PRAGMA query_only=ON")
    return conn


def _sha256_file(path):
    h = hashlib.sha256()
    with path.open("rb") as file:
        for piece in iter(lambda: file.read(1024 * 1024), b""):
            h.update(piece)
    return h.hexdigest()


def diagnose(*, root=None, db_file=None):
    """Inspect SQLite without modifying DB or creating files/directories."""
    root = Path(root or ROOT)
    db_file = Path(db_file or database_path())
    result = {
        "version": APP_VERSION, "database": str(db_file),
        "ok": False, "integrity": "не проверено", "tables_missing": [],
        "drawers": 0, "stock_items": 0,
        "review_pending": 0, "review_approved": 0,
        "review_excluded": 0, "review_priority": 0,
        "photos": 0, "missing_photos": 0, "warnings": [],
    }
    if not db_file.is_file():
        result["warnings"].append("Файл базы данных не найден. Диагностика ничего не создала.")
        return result
    try:
        with closing(_open_readonly(db_file)) as conn:
            check = conn.execute("PRAGMA integrity_check").fetchall()
            result["integrity"] = "ok" if check == [("ok",)] else "; ".join(
                str(row[0]) for row in check[:5]
            )
            tables = {
                row[0] for row in conn.execute(
                    "SELECT name FROM sqlite_master WHERE type='table'"
                ).fetchall()
            }
            result["tables_missing"] = sorted(set(REQUIRED_TABLES) - tables)
            def count(table, condition=""):
                if table not in tables:
                    return 0
                return conn.execute(
                    "SELECT COUNT(*) FROM " + table + (" WHERE " + condition if condition else "")
                ).fetchone()[0]

            result["drawers"] = count("drawers")
            result["stock_items"] = count("stock_items")
            result["review_pending"] = count("review_records", "state='pending'")
            result["review_approved"] = count("review_records", "state='approved'")
            result["review_excluded"] = count("review_records", "state='excluded'")
            result["review_priority"] = count("review_records", "state='pending' AND priority=1")
            result["photos"] = count("source_images")
            image_directory = root / "private_data" / "review_images"
            if "source_images" in tables:
                stored = conn.execute("SELECT stored_filename FROM source_images").fetchall()
                for (filename,) in stored:
                    # Filenames are generated by our importer. Reject paths
                    # accidentally written outside the image directory.
                    if not filename or Path(filename).name != filename:
                        result["missing_photos"] += 1
                    elif not (image_directory / filename).is_file():
                        result["missing_photos"] += 1
            if result["missing_photos"]:
                result["warnings"].append(
                    f"Нет {result['missing_photos']} исходных изображений; проверьте папку private_data."
                )
            if result["tables_missing"]:
                result["warnings"].append("Отсутствуют таблицы: " + ", ".join(result["tables_missing"]))
            result["ok"] = result["integrity"] == "ok" and not result["tables_missing"]
    except (sqlite3.Error, OSError, MaintenanceError) as exc:
        result["warnings"].append("Ошибка чтения базы: " + str(exc))
    return result


def backup(*, root=None, db_file=None):
    """Atomic, verified backup of SQLite and any local reference screenshots.

    Uses sqlite3.Connection.backup() so WAL content is included.
    ZIP is not encrypted; store private archives only in protected locations.
    """
    root = Path(root or ROOT)
    db_file = Path(db_file or database_path())
    if not db_file.is_file():
        raise MaintenanceError("База не найдена; нечего резервировать: " + str(db_file))
    backup_dir = root / "backups"
    backup_dir.mkdir(parents=True, exist_ok=True)
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S_%f")
    final = backup_dir / f"pharmdesk_{timestamp}.zip"
    db_temp = None
    zip_temp = None
    try:
        with tempfile.NamedTemporaryFile(prefix=".pharmdesk_db_", suffix=".sqlite3", dir=backup_dir, delete=False) as temp:
            db_temp = Path(temp.name)
        with closing(_open_readonly(db_file)) as source:
            with closing(sqlite3.connect(str(db_temp), timeout=8)) as destination:
                source.backup(destination, pages=256, sleep=0.02)
        with closing(sqlite3.connect(str(db_temp))) as conn:
            checked = conn.execute("PRAGMA integrity_check").fetchall()
            if checked != [("ok",)]:
                raise MaintenanceError("Не удалось подтвердить целостность копии SQLite.")
        with tempfile.NamedTemporaryFile(prefix=".pharmdesk_archive_", suffix=".zip", dir=backup_dir, delete=False) as temp:
            zip_temp = Path(temp.name)
        manifest = {
            "type": "PharmDesk local backup",
            "version": APP_VERSION,
            "created_at_utc": datetime.now(timezone.utc).isoformat(),
            "database": "database/pharmdesk.sqlite3",
            "files": {},
            "note": "Только локальная резервная копия. Не публиковать в GitHub.",
        }
        photo_directory = root / "private_data" / "review_images"
        with zipfile.ZipFile(zip_temp, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=6) as package:
            package.write(db_temp, "database/pharmdesk.sqlite3")
            manifest["files"]["database/pharmdesk.sqlite3"] = _sha256_file(db_temp)
            if photo_directory.is_dir():
                for photo in sorted(photo_directory.iterdir()):
                    if not photo.is_file() or photo.is_symlink():
                        continue
                    # The application saves images using safe hash-derived filenames.
                    if photo.suffix.lower() not in (".png", ".jpg", ".jpeg"):
                        continue
                    entry_name = "review_images/" + photo.name
                    package.write(photo, entry_name)
                    manifest["files"][entry_name] = _sha256_file(photo)
            package.writestr("manifest.json", json.dumps(manifest, ensure_ascii=False, indent=2))
        with zipfile.ZipFile(zip_temp) as package:
            damaged = package.testzip()
            if damaged is not None:
                raise MaintenanceError("Ошибка проверки архива: " + damaged)
            saved_manifest = json.loads(package.read("manifest.json"))
            for filename, expected in saved_manifest["files"].items():
                if hashlib.sha256(package.read(filename)).hexdigest() != expected:
                    raise MaintenanceError("Контрольная сумма не совпала: " + filename)
        os.replace(zip_temp, final)
        zip_temp = None
        return {"path": str(final), "files": len(manifest["files"]), "version": APP_VERSION}
    finally:
        for path in (db_temp, zip_temp):
            if path is not None:
                path.unlink(missing_ok=True)


def main(argv=None):
    parser = argparse.ArgumentParser(description="Безопасное обслуживание PharmDesk")
    commands = parser.add_subparsers(dest="action", required=True)
    commands.add_parser("backup", help="Создать резервную копию SQLite и фотографий")
    commands.add_parser("diagnose", help="Проверить базу (только чтение)")
    commands.add_parser("version", help="Показать версию программы")
    args = parser.parse_args(argv)
    try:
        if args.action == "version":
            print("PharmDesk", APP_VERSION)
            return 0
        if args.action == "backup":
            info = backup()
            print("Резервная копия создана:", info["path"])
            print("Проверено файлов:", info["files"])
            print("Архив не зашифрован: храните его в защищённом месте.")
            return 0
        result = diagnose()
        print("PharmDesk", result["version"])
        print("База:", result["database"])
        print("Целостность:", result["integrity"])
        print("Ящиков:", result["drawers"])
        print("Товарных записей:", result["stock_items"])
        print("Ожидают сверки:", result["review_pending"])
        print("Сомнительных ожидающих:", result["review_priority"])
        print("Подтверждено:", result["review_approved"])
        print("Исключено:", result["review_excluded"])
        print("Изображений зарегистрировано:", result["photos"])
        print("Отсутствует изображений:", result["missing_photos"])
        for warning in result["warnings"]:
            print("Внимание:", warning)
        print("Результат:", "База структурно исправна" if result["ok"] else "Есть проблемы")
        return 0 if result["ok"] else 1
    except (MaintenanceError, OSError, sqlite3.Error) as exc:
        print("Ошибка:", exc, file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
